
clc;
clear;
close all;


%% ================================================================
% LOAD DATA
% ================================================================

filename = 'state_history_OR.dat';

data = readtable(filename);


%% ================================================================
% EXTRACT DATA
% ================================================================

steps = data{:,1};
V     = data{:,2};
n     = data{:,3};
f     = data{:,4};
Ca    = data{:,5};


%% ================================================================
% REMOVE INVALID VALUES
% ================================================================

valid = ...
    ~(isnan(steps) | ...
      isnan(V) | ...
      isnan(n) | ...
      isnan(f) | ...
      isnan(Ca));

steps = steps(valid);
V     = V(valid);
n     = n(valid);
f     = f(valid);
Ca    = Ca(valid);


%% ================================================================
% TRUNCATE TO FIRST 32000 POINTS
% ================================================================

max_len = ...
    min(32000, length(steps));

steps = steps(1:max_len);
V     = V(1:max_len);
n     = n(1:max_len);
f     = f(1:max_len);
Ca    = Ca(1:max_len);


%% ================================================================
% MODEL PARAMETERS_FILE2
% ================================================================

gCa = 4;
gk  = 0.3;
gSK = 2;
gBK = 2;

VCa = 50;
Vk  = -82.5;

Vm = -20.84;
Sm = 8.68;

Vn = -14.99;
Sn = 29.916;

Vf = -35;
Sf = 4.227;

Ks = 1;


%% ================================================================
% GATING VARIABLES
%
% Calculated using the ORIGINAL physiological voltage.
% ================================================================

minf = ...
    1 ./ ...
    (1 + exp((Vm - V) ./ Sm));

ninf = ...
    1 ./ ...
    (1 + exp((Vn - V) ./ Sn));

finf = ...
    1 ./ ...
    (1 + exp((Vf - V) ./ Sf));

sinf = ...
    (Ca.^2) ./ ...
    (Ca.^2 + Ks^2);


%% ================================================================
% IONIC CURRENTS
%
% Calculated using ORIGINAL V.
% ================================================================

ICa = ...
    gCa .* ...
    minf .* ...
    (V - VCa);

IK = ...
    gk .* ...
    n .* ...
    (V - Vk);

ISK = ...
    gSK .* ...
    sinf .* ...
    (V - Vk);

IBK = ...
    gBK .* ...
    f .* ...
    (V - Vk);


%% ================================================================
% EXPAND TO 40000 PLOTTING POINTS
% ================================================================

N = ...
    40000;

idx_old = ...
    1:max_len;

idx_new = ...
    linspace( ...
    1, ...
    max_len, ...
    N);


%% ================================================================
% INTERPOLATE VOLTAGE AND CURRENTS
% ================================================================

V_plot = ...
    interp1( ...
    idx_old, ...
    V, ...
    idx_new, ...
    'nearest', ...
    'extrap');

ICa_plot = ...
    interp1( ...
    idx_old, ...
    ICa, ...
    idx_new, ...
    'nearest', ...
    'extrap');

IK_plot = ...
    interp1( ...
    idx_old, ...
    IK, ...
    idx_new, ...
    'nearest', ...
    'extrap');

ISK_plot = ...
    interp1( ...
    idx_old, ...
    ISK, ...
    idx_new, ...
    'nearest', ...
    'extrap');

IBK_plot = ...
    interp1( ...
    idx_old, ...
    IBK, ...
    idx_new, ...
    'nearest', ...
    'extrap');


%% ================================================================
% DEFINE TIME AXIS IN MILLISECONDS
%
% Total recording duration = 2 s = 2000 ms
% ================================================================

totalTime_ms = ...
    2000;

time_plot = ...
    linspace( ...
    0, ...
    totalTime_ms, ...
    N);


%% ================================================================
% BLUE COLOUR PALETTE
% ================================================================

c1 = [0.65 0.85 1.00];
c2 = [0.30 0.60 0.95];
c3 = [0.10 0.35 0.80];
c4 = [0.05 0.15 0.50];


%% ================================================================
% CREATE FIGURE
% ================================================================

figure( ...
    'Color','w');


%% ================================================================
% LEFT Y-AXIS: ORIGINAL VOLTAGE
% ================================================================

yyaxis left

hV = ...
    plot( ...
    time_plot, ...
    V_plot, ...
    'Color', ...
    [0.85 0.15 0.15], ...
    'LineWidth', ...
    1.5);

hold on;


ylabel( ...
    'Voltage (mV)', ...
    'FontSize', ...
    38);


% Original physiological voltage range
ylim( ...
    [-90 40]);


ax = ...
    gca;

ax.YAxis(1).Color = ...
    'k';


%% ================================================================
% RIGHT Y-AXIS: IONIC CURRENTS
% ================================================================

yyaxis right


hCa = ...
    plot( ...
    time_plot, ...
    ICa_plot, ...
    'Color', ...
    c1, ...
    'LineWidth', ...
    1.7);


hK = ...
    plot( ...
    time_plot, ...
    IK_plot, ...
    'Color', ...
    c2, ...
    'LineWidth', ...
    1.7);


hSK = ...
    plot( ...
    time_plot, ...
    ISK_plot, ...
    'Color', ...
    c3, ...
    'LineWidth', ...
    1.7);


hBK = ...
    plot( ...
    time_plot, ...
    IBK_plot, ...
    'Color', ...
    c4, ...
    'LineWidth', ...
    1.2, ...
    'LineStyle', ...
    '--');


ylabel( ...
    'Ionic Currents (pA)', ...
    'FontSize', ...
    38, ...
    'Color', ...
    'b');


ax.YAxis(2).Color = ...
    'b';


%% ================================================================
% X AXIS: TIME IN MILLISECONDS
% ================================================================

xlabel( ...
    'Time (ms)', ...
    'FontSize', ...
    38);


xlim( ...
    [0 2000]);


xticks( ...
    0:500:2000);


%% ================================================================
% GENERAL FORMATTING
% ================================================================

grid off;
box off;

ax = ...
    gca;

ax.FontSize = ...
    38;

ax.LineWidth = ...
    1.2;

ax.TickDir = ...
    'out';

ax.XColor = ...
    'k';

% Keep individual yyaxis colours
ax.YAxis(1).Color = ...
    'k';

ax.YAxis(2).Color = ...
    'b';


%% ================================================================
% LEGEND
% ================================================================

legend( ...
    [hV hCa hK hSK hBK], ...
    { ...
    'V', ...
    'I_{Ca}', ...
    'I_{K}', ...
    'I_{SK}', ...
    'I_{BK}'}, ...
    'Location', ...
    'northeast', ...
    'Orientation', ...
    'horizontal', ...
    'Box', ...
    'off');


hold off;
